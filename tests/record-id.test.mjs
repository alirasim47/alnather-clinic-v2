import test from "node:test";
import assert from "node:assert/strict";
import { assertSingleCreate, newRecordIdentity } from "../lib/server/record-id.mjs";

test("new patient identities use server UUIDs and derive a new file number without changing legacy IDs", () => {
  const first = newRecordIdentity("patients");
  const second = newRecordIdentity("patients");
  assert.match(first.id, /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i);
  assert.notEqual(first.id, second.id);
  assert.equal(first.fileNo, `P-${first.id.replaceAll("-", "").slice(0, 12).toUpperCase()}`);
  assert.doesNotMatch(first.id, /^\d+$/);
});

test("new examiner identity is a UUID generated by the server helper", () => {
  const identity = newRecordIdentity("examiners");
  assert.match(identity.id, /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i);
  assert.equal(Object.hasOwn(identity, "fileNo"), false);
});

test("a no-op create insert is reported as an HTTP 409 conflict", () => {
  assert.doesNotThrow(() => assertSingleCreate(1));
  assert.throws(() => assertSingleCreate(0), { status: 409 });
});
